"""run_import_core trailing-footer detection: a file whose tail is non-transaction documentation
(totals, "generated by" lines, end-of-report markers) should set `trailing_non_transaction_suspected`
so the import UI forces a raw-file review, while the real transactions above still import. The signal
is a run of consecutive unparseable rows that is still open at end-of-file; a valid row resets it, so a
bad row in the *middle* of the data must NOT trip it. This pins that contract — it drives the heuristic
that is otherwise only reachable through a hand-crafted import in the browser."""

import tempfile
import unittest
from contextlib import contextmanager
from pathlib import Path

from backend.db.database import get_db, init_db, reset_current_db_path, set_current_db_path
from backend.routers.import_export.core import run_import_core


# A realistic export tail: a totals line then two documentation lines, none of which name a mappable
# account, so each is recorded as a footer-like error. Vendors are large generic brands; no PII.
FOOTER_BLOCK = (
    "Totals,,63.45,\n"
    "Generated by account export,,,\n"
    "End of report,,,\n"
)


class TrailingFooterDetectionTests(unittest.TestCase):
    def setUp(self):
        self.tempdir = tempfile.TemporaryDirectory()
        self.db_path = Path(self.tempdir.name) / "footer.db"
        init_db(str(self.db_path))
        with get_db(str(self.db_path)) as conn:
            conn.execute(
                """INSERT INTO account (id, external_account_id, provider, name, display_name, type)
                   VALUES ('acc-chk', NULL, 'manual', 'Checking', 'Checking', 'depository')"""
            )

    def tearDown(self):
        self.tempdir.cleanup()

    @contextmanager
    def _use_db_path(self):
        token = set_current_db_path(str(self.db_path))
        try:
            yield
        finally:
            reset_current_db_path(token)

    def _cfg(self):
        return {
            "account_map": {"Checking": "acc-chk"},
            "column_map": {"date": "Date", "amount": "Amount", "description": "Description", "account": "Account"},
            "date_format": "%Y-%m-%d",
            "amount_convention": "single_signed",
            "apply_categorization": False,
            "use_imported_categories": False,
        }

    def _run(self, csv):
        with self._use_db_path():
            return run_import_core(csv, self._cfg(), filename="bank.csv")

    def test_trailing_footer_block_is_flagged_and_real_rows_import(self):
        csv = (
            "Date,Description,Amount,Account\n"
            "2026-01-05,Amazon,54.20,Checking\n"
            "2026-01-06,Starbucks,6.50,Checking\n"
            "2026-01-07,Transit,2.75,Checking\n"
            + FOOTER_BLOCK
        )
        result = self._run(csv)
        self.assertTrue(result.get("trailing_non_transaction_suspected"))
        # First footer line is the 4th data row -> source line 5 (header on line 1, no skipped rows).
        self.assertEqual(result.get("trailing_error_start_row"), 5)
        # The three real transactions above the footer still import.
        self.assertEqual(result.get("imported"), 3)

    def test_clean_file_is_not_flagged(self):
        csv = (
            "Date,Description,Amount,Account\n"
            "2026-01-05,Amazon,54.20,Checking\n"
            "2026-01-06,Starbucks,6.50,Checking\n"
        )
        result = self._run(csv)
        self.assertFalse(result.get("trailing_non_transaction_suspected"))
        self.assertIsNone(result.get("trailing_error_start_row"))
        self.assertEqual(result.get("imported"), 2)

    def test_error_in_the_middle_does_not_flag_a_footer(self):
        # A single bad row surrounded by valid rows is a normal validation error, not a trailing footer:
        # the valid row after it resets the run, so the file tail is clean and the flag stays off.
        csv = (
            "Date,Description,Amount,Account\n"
            "2026-01-05,Amazon,54.20,Checking\n"
            "Totals,,63.45,\n"
            "2026-01-07,Transit,2.75,Checking\n"
        )
        result = self._run(csv)
        self.assertFalse(result.get("trailing_non_transaction_suspected"))
        self.assertEqual(result.get("imported"), 2)


if __name__ == "__main__":
    unittest.main()
